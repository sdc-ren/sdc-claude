// tf knowledge map `runtime` — what runs without a user's request: cron jobs, queues and workers, jobs added to a
// queue, events and pub/sub, routes that look like webhooks, socket events the server emits. A webhook here is a
// route whose path says so (webhook, callback, ipn, notify, hook) — flagged, not concluded.
import runtimeReader from '../frameworks/runtime.mjs'
import { isSource } from '../scan.mjs'
import { ROUTERS, modelOf } from './contracts.mjs'
import { perRepo, tsv, versions } from './util.mjs'

const KINDS = [
  ['cron', 'Cron and timers', 'what runs on a schedule'],
  ['queue', 'Queues', 'where a queue is created'],
  ['worker', 'Workers', 'what processes a queue'],
  ['job', 'Jobs added to a queue', 'who puts work on a queue'],
  ['event', 'Events', 'in-process events: who emits, who listens'],
  ['pubsub', 'Pub/sub', 'Redis channels: who publishes, who subscribes'],
  ['webhook', 'Webhook-like routes', 'routes a third party probably calls (by path only)'],
  ['socket', 'Socket events the server emits', 'pushed to clients without a request'],
]
const WEBHOOK = /(^|\/)[^/]*(webhook|callback|ipn|notify|hook)s?([\/-]|$)|[-_]return$/i

function items(ctx) {
  const out = perRepo(ctx, 'runtime', (rd) => (runtimeReader.detect(rd) ? runtimeReader.extract(rd, { isSource }) : [])).flatMap((x) => x.items.map((i) => ({ ...i, repo: x.key })))
  const model = ctx.profile.repos.some((r) => ROUTERS.some((f) => f.detect(ctx.reader(r)))) ? modelOf(ctx) : { routes: [], sockets: [] }
  for (const r of model.routes) if (WEBHOOK.test(r.path)) out.push({ kind: 'webhook', name: `${r.method} ${r.path}`, detail: r.guards.length ? `guards: ${r.guards.join(', ')}` : 'no guard found', at: r.at, in: r.framework, repo: r.repo })
  for (const s of model.sockets) if (s.side === 'server' && s.dir === 'emit') out.push({ kind: 'socket', name: s.event, detail: 'emit', at: s.at, in: '', repo: s.repo })
  return out
}

function render(ctx) {
  const all = items(ctx)
  const lines = ['# Runtime — what runs without a request', '', `Generated by tf from the base branches — do not edit. ${all.length} item(s). Grep \`runtime/index.tsv\` for a name.`, '']
  for (const [kind, title, what] of KINDS) {
    const list = all.filter((i) => i.kind === kind).sort((a, b) => a.repo.localeCompare(b.repo) || a.name.localeCompare(b.name))
    if (!list.length) continue
    lines.push(`## ${title} (${list.length})`, '', `_${what}_`, '', '| name | detail | in | repo | at |', '|---|---|---|---|---|')
    for (const i of list) lines.push(`| \`${i.name.replace(/\|/g, '\\|')}\` | ${i.detail.replace(/\|/g, '\\|')} | ${i.in || ''} | ${i.repo} | \`${i.at}\` |`)
    lines.push('')
  }
  lines.push('Names given through a constant of the repo are resolved; a name built at run time is shown as written. Check in the code (codegraph) before relying on it.', '')
  const rows = [['kind', 'name', 'detail', 'in', 'repo', 'at'].join('\t'), ...all.map((i) => [i.kind, i.name, i.detail, i.in, i.repo, i.at].map(tsv).join('\t'))]
  return { 'runtime/async.md': lines.join('\n'), 'runtime/index.tsv': `${rows.join('\n')}\n` }
}

export default {
  name: 'runtime',
  answers: 'What runs without a request: cron jobs, queues and workers, events and pub/sub, webhook-like routes, socket events the server emits',
  // Only when something was found: a workspace with routes but no job, event or webhook gets no empty map.
  applies: (ctx) => items(ctx).length > 0,
  sources: (ctx) => versions(ctx),
  generate: render,
}
