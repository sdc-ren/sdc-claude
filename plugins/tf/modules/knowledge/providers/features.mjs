// tf knowledge map `features` — feature → screen → endpoint, only from tags the code declares in its comments
// (config `- Feature tags: @screen, @api, @role`; default @feature, @screen, @role). Nothing is guessed: no tag
// found, no map.
import { domainOf, modelOf, ROUTERS } from './contracts.mjs'
import { once, slug, tsv, versions } from './util.mjs'

export const DEFAULT_TAGS = ['@feature', '@screen', '@role']
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

export const tagsOf = (knowledge = {}) => {
  const given = String(knowledge.featureTags || '').split(/[,\s]+/).map((t) => t.trim()).filter(Boolean).map((t) => (t.startsWith('@') ? t : `@${t}`))
  return given.length ? given : DEFAULT_TAGS
}

/** Tagged places: [{ repo, file, line, tags: { '@screen': 'x', … } }] — tags on nearby comment lines are one place.
 *  A line can hold several tags (`@screen orders  @api list-orders`); a value ends where the next tag starts. */
export function findTagged(reader, tags) {
  const wanted = new Set(tags)
  const hits = reader.grep(`(${tags.map(esc).join('|')})`, (f) => !/(^|\/)(node_modules|test|tests|__tests__)\//.test(f) && !/\.(md|json|lock|ya?ml)$/.test(f))
  const out = []
  for (const h of hits) {
    if (!/^\s*(\*|\/\/|\/\*|#|<!--|\{\/\*)/.test(h.text)) continue
    const body = h.text.replace(/\*\/\}?.*$|-->.*$/, '')
    const found = {}
    for (const m of body.matchAll(/(?:^|[\s*/[(])(@[\w-]+)[:\s]+((?:(?![\s[(]@[\w-]).)+)/g)) {
      const value = m[2].replace(/[\])]\s*$/, '').trim()
      // `<screen>` and the like are a template in a doc comment, not a value.
      if (wanted.has(m[1]) && value && !/^<.*>$|^<\w+>/.test(value)) found[m[1]] = value
    }
    if (!Object.keys(found).length) continue
    const last = out[out.length - 1]
    if (last && last.file === h.file && h.line - last.end <= 6 && !Object.keys(found).some((k) => k in last.tags)) { Object.assign(last.tags, found); last.end = h.line; continue }
    out.push({ file: h.file, line: h.line, end: h.line, tags: found })
  }
  return out
}

const model = (ctx) => once(ctx, 'features', () => {
  const tags = tagsOf(ctx.knowledge)
  const items = ctx.profile.repos.flatMap((r) => findTagged(ctx.reader(r), tags).map((t) => ({ ...t, repo: r.key })))
  return { tags, items }
})

function render(ctx) {
  const { tags, items } = model(ctx)
  const prefixes = String(ctx.knowledge.apiPrefix || '').split(',').map((x) => x.trim()).filter(Boolean)
  const routes = ctx.profile.repos.some((r) => ROUTERS.some((f) => f.detect(ctx.reader(r)))) ? modelOf(ctx).routes : []
  // The route declared right under a tag (same file, within 20 lines).
  const routeOf = (t) => routes.find((r) => r.repo === t.repo && r.at.startsWith(`${t.file}:`) && +r.at.split(':').pop() > t.line - 1 && +r.at.split(':').pop() <= t.end + 20)
  // Pages: one per value of the coarsest tag most places carry (fewest values); with more than 80 values, one per
  // area of the code instead (the route's first segment, else the file's folder), tags still shown per line.
  const common = tags.filter((x) => items.filter((t) => x in t.tags).length * 2 >= items.length)
  const distinct = (x) => new Set(items.map((t) => t.tags[x]).filter(Boolean)).size
  const by = (common.length ? common : tags).reduce((a, b) => (distinct(b) < distinct(a) ? b : a))
  const area = (t) => { const r = routeOf(t); if (r) return domainOf(r.path, prefixes).split('-')[0]; const d = t.file.split('/'); return d[d.length - 2] || 'root' }
  const pageKey = distinct(by) > 80 ? (t) => `area ${area(t)}` : (t) => `${by} ${t.tags[by] || '(untagged)'}`
  const groups = new Map()
  for (const t of items) {
    const k = pageKey(t)
    if (!groups.has(k)) groups.set(k, [])
    groups.get(k).push(t)
  }
  const out = {}
  const rows = [['tags', 'repo', 'at', 'route', ...tags].join('\t')]
  const readme = ['# Features', '', `Generated by tf from the tags the code declares (${tags.map((t) => `\`${t}\``).join(', ')}; config \`- Feature tags:\`) — do not edit. Only what is tagged is here; nothing is inferred.`, '', `Pages: ${distinct(by) > 80 ? `one per area of the code (\`${by}\` has ${distinct(by)} values)` : `one per \`${by}\``}. Grep \`features/index.tsv\` for a tag value.`, '', '| page for | places | page |', '|---|---|---|']
  const used = new Set()
  for (const [k, list] of [...groups].sort((a, b) => a[0].localeCompare(b[0]))) {
    const value = k.slice(k.indexOf(' ') + 1)
    let name = slug(distinct(by) > 80 ? value : `${by.slice(1)}-${value}`)
    if (used.has(name)) name = `${name}-${used.size}`
    used.add(name)
    const page = `features/${name}.md`
    const lines = [`# ${k.startsWith('area ') ? `Area ${value}` : `${by} ${value}`}`, '', `${list.length} tagged place(s).`, '', `| ${tags.join(' | ')} | route | at |`, `|${tags.map(() => '---|').join('')}---|---|`]
    for (const t of [...list].sort((a, b) => String(a.tags[by] || '').localeCompare(String(b.tags[by] || '')) || a.file.localeCompare(b.file) || a.line - b.line)) {
      const r = routeOf(t)
      lines.push(`| ${tags.map((x) => (t.tags[x] || '').replace(/\|/g, '\\|')).join(' | ')} | ${r ? `**${r.method}** \`${r.path}\`` : '—'} | ${t.repo} \`${t.file}:${t.line}\` |`)
      rows.push([Object.keys(t.tags).join(' '), t.repo, `${t.file}:${t.line}`, r ? `${r.method} ${r.path}` : '', ...tags.map((x) => t.tags[x] || '')].map(tsv).join('\t'))
    }
    lines.push('')
    out[page] = lines.join('\n')
    readme.push(`| ${value.replace(/\|/g, '\\|')} | ${list.length} | \`${page}\` |`)
  }
  readme.push('')
  out['features/README.md'] = readme.join('\n')
  out['features/index.tsv'] = `${rows.join('\n')}\n`
  return out
}

export default {
  name: 'features',
  answers: 'Which features, screens and roles the code tags, and the endpoint under each tag (only what is tagged)',
  applies: (ctx) => model(ctx).items.length > 0,
  sources: (ctx) => versions(ctx, tagsOf(ctx.knowledge).join(',')),
  generate: render,
}
