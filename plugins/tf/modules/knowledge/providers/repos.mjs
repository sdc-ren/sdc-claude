// tf knowledge map `repos` — one page per repo: stack, how it runs, its folders, its docs, its domain folders.
// Applies to every workspace, one repo or many. Read from origin/<base> (source.mjs).

const tsvCell = (s) => String(s ?? '').replace(/[\t\n\r]+/g, ' ')

// Folders two levels deep with how many files each holds — the shape of a repo at a glance.
function tree(files, maxRows = 60) {
  const count = new Map()
  for (const f of files) {
    const parts = f.split('/')
    if (parts.length < 2) continue
    const top = parts[0]
    count.set(top, (count.get(top) || 0) + 1)
    if (parts.length > 2) { const two = `${top}/${parts[1]}`; count.set(two, (count.get(two) || 0) + 1) }
  }
  const rows = [...count.entries()].sort((a, b) => a[0].localeCompare(b[0]))
  const top = rows.filter(([k]) => !k.includes('/'))
  const out = []
  for (const [k, n] of top) {
    out.push(`- \`${k}/\` — ${n} files`)
    const subs = rows.filter(([s]) => s.startsWith(`${k}/`)).sort((a, b) => b[1] - a[1]).slice(0, 8)
    for (const [s, m] of subs) out.push(`  - \`${s}/\` — ${m}`)
    if (out.length >= maxRows) { out.push('- …'); break }
  }
  return out.join('\n')
}

function page(r, reader) {
  const files = reader.files()
  const lines = [
    `# ${r.key} — \`${r.path}\``,
    '',
    `Read from \`${reader.ref}\`${reader.ref.startsWith('origin/') ? ` (${reader.version.slice(0, 10)})` : ''}. Generated by tf — do not edit; \`Generate\` rewrites it.`,
    '',
    '## Stack',
    `- ${r.stack.join(', ') || 'not recognised'}${r.monorepo ? ` · monorepo: ${r.monorepo}` : ''}`,
    `- Package manager: ${r.packageManager || '—'}${r.lockfile ? ` (\`${r.lockfile}\`${r.reusable ? ` → \`${r.reusable}\`` : ''})` : ''}`,
    `- Base branch: \`${r.base || '—'}\` · ${files.length} tracked files`,
  ]
  const scripts = Object.entries(r.scripts)
  if (scripts.length) lines.push('', '## Commands', ...scripts.map(([k, v]) => `- \`${k}\`: \`${v}\``))
  if (r.ports.length) lines.push('', '## Ports', ...r.ports.map((p) => `- ${p}`))
  if (r.env.names.length) lines.push('', `## Environment (names only, from \`${r.env.file}\`)`, r.env.names.map((n) => `\`${n}\``).join(' · '))
  const docs = [...r.docs, ...r.openapi]
  if (docs.length) lines.push('', '## Docs to read first', ...docs.map((d) => `- \`${r.path === './' ? '' : r.path}${d}\``))
  if (r.domains.names.length) lines.push('', `## Domain folders (\`${r.domains.dir}/\`)`, r.domains.names.map((n) => `\`${n}\``).join(' · '))
  lines.push('', '## Folders', tree(files), '')
  return lines.join('\n')
}

export default {
  name: 'repos',
  answers: 'Which repos there are; for each: stack, how to run and test it, ports, env names, its docs, its domain folders and folder layout',
  applies: (ctx) => ctx.profile.repos.length > 0,
  sources: (ctx) => Object.fromEntries(ctx.profile.repos.map((r) => [r.key, ctx.reader(r).version])),
  generate(ctx) {
    const out = {}
    const rows = [['key', 'path', 'base', 'stack', 'package manager', 'domains', 'page'].join('\t')]
    for (const r of ctx.profile.repos) {
      out[`repos/${r.key}.md`] = page(r, ctx.reader(r))
      rows.push([r.key, r.path, r.base, r.stack.join(', '), r.packageManager, r.domains.names.join(' '), `repos/${r.key}.md`].map(tsvCell).join('\t'))
    }
    out['repos/index.tsv'] = `${rows.join('\n')}\n`
    return out
  },
}
