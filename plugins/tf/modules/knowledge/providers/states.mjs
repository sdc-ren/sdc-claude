// tf knowledge map `states` — the state enums of the code and where each value is written. An enum is kept when
// its name looks like a state (default /status|state|phase|stage|step/i; config `- State enums: <regex>`).
import { findEnums, findWrites } from '../frameworks/enums.mjs'
import { perRepo, slug, tsv, versions } from './util.mjs'

export const DEFAULT_STATES = 'status|state|phase|stage|step'

function filterOf(knowledge) {
  try { return new RegExp(knowledge.stateEnums || DEFAULT_STATES, 'i') } catch { return new RegExp(DEFAULT_STATES, 'i') }
}

const enumsOf = (ctx) => perRepo(ctx, 'states', (rd) => findEnums(rd, filterOf(ctx.knowledge)))

function render(ctx) {
  const out = {}
  const rows = [['enum', 'kind', 'repo', 'at', 'values', 'page'].join('\t')]
  const readme = ['# States', '', `Generated by tf from the base branches — do not edit. Enums whose name matches \`/${ctx.knowledge.stateEnums || DEFAULT_STATES}/i\` (config \`- State enums:\`), with the places each value is written.`, '', '| enum | values | repo | page |', '|---|---|---|---|']
  const used = new Set()
  for (const { key, reader, items: enums } of enumsOf(ctx)) {
    const writes = findWrites(reader, enums)
    for (const e of [...enums].sort((a, b) => a.name.localeCompare(b.name))) {
      let name = `${slug(e.name)}`
      if (used.has(name)) name = `${name}-${slug(key)}`
      used.add(name)
      const page = `states/${name}.md`
      const lines = [`# ${e.name}`, '', `${key} · \`${e.at}\` · ${e.kind}`, '', '| value | stored as | written at |', '|---|---|---|']
      for (const v of e.values) {
        const at = writes[`${e.name}.${v.key}`] || []
        lines.push(`| \`${v.key}\` | \`${v.value}\` | ${at.length ? at.map((a) => `\`${a}\``).join('<br>') : '—'} |`)
      }
      lines.push('', 'Writes are lines that set the value (assignment or object key), not comparisons; a value set from a variable is not followed.', '')
      out[page] = lines.join('\n')
      readme.push(`| \`${e.name}\` | ${e.values.length} | ${key} | \`${page}\` |`)
      rows.push([e.name, e.kind, key, e.at, e.values.map((v) => v.key).join(' '), page].map(tsv).join('\t'))
    }
  }
  readme.push('')
  out['states/README.md'] = readme.join('\n')
  out['states/index.tsv'] = `${rows.join('\n')}\n`
  return out
}

export default {
  name: 'states',
  answers: 'Which state enums there are, their values, and where each value is written',
  applies: (ctx) => enumsOf(ctx).length > 0,
  sources: (ctx) => versions(ctx, ctx.knowledge.stateEnums || ''),
  generate: render,
}
