// tf knowledge map `erd` — tables and models from the code (Prisma, Sequelize, TypeORM, Mongoose; SQL migrations
// when no ORM), their columns and relations, and the files that use each model. Not read from a live database.
import { findModels, usersOf } from '../frameworks/models.mjs'
import { perRepo, slug, tsv, versions } from './util.mjs'

const modelsOf = (ctx) => perRepo(ctx, 'erd', findModels)

// A small diagram around one model: its relations both ways.
function mermaid(m, all) {
  const id = (n) => n.replace(/\W/g, '_')
  const edges = new Set()
  const sym = { belongsTo: '}o--||', hasMany: '||--o{', hasOne: '||--o|', belongsToMany: '}o--o{', manyToOne: '}o--||', oneToMany: '||--o{', oneToOne: '||--||', manyToMany: '}o--o{', ref: '}o--||', references: '}o--||' }
  for (const r of m.rels) edges.add(`  ${id(m.name)} ${sym[r.kind] || '}o--||'} ${id(r.target)} : "${r.kind}${r.key ? ` ${r.key}` : ''}"`)
  for (const o of all) for (const r of o.rels) if (r.target === m.name && o.name !== m.name) edges.add(`  ${id(o.name)} ${sym[r.kind] || '}o--||'} ${id(m.name)} : "${r.kind}${r.key ? ` ${r.key}` : ''}"`)
  return edges.size ? ['```mermaid', 'erDiagram', ...[...edges].slice(0, 40), '```', ''] : []
}

function render(ctx) {
  const out = {}
  const rows = [['model', 'table', 'orm', 'repo', 'at', 'columns', 'relations', 'used_by', 'page'].join('\t')]
  const readme = ['# ERD', '', 'Generated by tf from the models in the code (base branches) — do not edit. Not read from a live database: columns added only by a migration or by hand are missing.', '', '| model | table | columns | relations | used by | repo | page |', '|---|---|---|---|---|---|---|']
  const used = new Set()
  for (const { key, reader, items: models } of modelsOf(ctx)) {
    const users = usersOf(reader, models)
    for (const m of [...models].sort((a, b) => a.name.localeCompare(b.name))) {
      let name = slug(m.table || m.name)
      if (used.has(name)) name = `${name}-${slug(key)}`
      used.add(name)
      const page = `erd/${name}.md`
      const by = users[m.name] || []
      const incoming = models.filter((o) => o.name !== m.name && o.rels.some((r) => r.target === m.name))
      const lines = [`# ${m.name}${m.table && m.table !== m.name ? ` (table \`${m.table}\`)` : ''}`, '', `${key} · ${m.orm} · \`${m.at || '—'}\``, '', '## Columns', '']
      lines.push(...(m.cols.length ? ['| column | type |', '|---|---|', ...m.cols.map((c) => `| \`${c.name}\` | ${c.type || '—'} |`)] : ['_None read (declared in a way this map does not follow)._']), '')
      lines.push('## Relations', '', ...(m.rels.length ? m.rels.map((r) => `- ${r.kind} **${r.target}**${r.key ? ` via \`${r.key}\`` : ''}`) : ['_None declared on this model._']))
      if (incoming.length) lines.push('', `Referenced by: ${incoming.map((o) => `**${o.name}**`).join(', ')}`)
      lines.push('', ...mermaid(m, models), `## Used by (${by.length}${by.length >= 15 ? '+' : ''})`, '', ...(by.length ? by.map((f) => `- \`${f}\``) : ['_No service, controller, route, job or repository file names it._']), '')
      out[page] = lines.join('\n')
      readme.push(`| \`${m.name}\` | ${m.table || '—'} | ${m.cols.length} | ${m.rels.length} | ${by.length} | ${key} | \`${page}\` |`)
      rows.push([m.name, m.table, m.orm, key, m.at, m.cols.map((c) => c.name).join(' '), m.rels.map((r) => `${r.kind}:${r.target}`).join(' '), by.join(' '), page].map(tsv).join('\t'))
    }
  }
  readme.push('', '"Used by" lists service, controller, route, handler, job, worker and repository files that name the model, outside its own file (at most 15).', '')
  out['erd/README.md'] = readme.join('\n')
  out['erd/index.tsv'] = `${rows.join('\n')}\n`
  return out
}

export default {
  name: 'erd',
  answers: 'Which tables and models there are, their columns and relations, and which services use each',
  applies: (ctx) => modelsOf(ctx).length > 0,
  sources: (ctx) => versions(ctx),
  generate: render,
}
